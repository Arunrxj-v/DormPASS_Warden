import 'package:flutter/material.dart';

/// Every failure the app can present, as a typed code + user message.
/// Codes 1:1 with the backend contract (docs/API.md); client-only codes are
/// prefixed `local_`.
class AppException implements Exception {
  const AppException(this.code, {this.message, this.details = const {}});

  /// Machine-readable code, e.g. `outside_geofence`.
  final String code;

  /// Server-provided message if available.
  final String? message;

  /// Extra structured data (distance_m, similarity, ...).
  final Map<String, dynamic> details;

  bool get isAuthExpired => code == 'token_invalid' || code == 'token_revoked';

  /// User-facing message.
  ///
  /// The server's message wins whenever one came back: it is written against
  /// the failure that actually happened. The client table is the fallback
  /// for codes the server sent no text for — all `local_*` codes, plus any
  /// transport-level failure. Only codes reachable from the warden console
  /// are listed; student-app codes (attendance, geofence) cannot occur here.
  String get displayMessage =>
      message ??
      localizedMessage(code) ??
      'Something went wrong. Please try again.';

  static String? localizedMessage(String code) {
    switch (code) {
      // --- Auth ---
      case 'invalid_credentials':
        return 'Incorrect username or password. Try again.';
      case 'token_invalid':
      case 'token_revoked':
        return 'Your session expired. Please sign in again.';
      case 'account_inactive':
        return 'This account is inactive. Contact an administrator.';
      // --- Transport ---
      // DEVICE OFFLINE: the phone has no network interface at all.
      case 'local_device_offline':
        return 'This phone has no internet connection. Turn on Wi-Fi or '
            'mobile data and try again — the server was not the problem.';
      // API UNREACHABLE: the phone IS online, but the configured API address
      // did not answer (wrong URL, server down, DNS failure, timeout).
      case 'local_api_unreachable':
        return 'The HostelPass server could not be reached. This phone has a '
            'network connection, but the configured API address is not '
            'responding.';
      case 'local_bad_certificate':
        return "The server's security certificate could not be verified. "
            'Connection refused.';
      case 'local_server_error':
        return 'The HostelPass server is reachable but hit an internal '
            'error. Try again shortly.';
      // Server answered, but not with HostelPass API data — the API is not
      // deployed/routed at this address (e.g. a reverse proxy serving the
      // Admin Console for API paths).
      case 'local_api_not_hostelpass':
        return 'This address answered, but not with HostelPass API data. '
            'The API is not deployed or not routed there.';
      // --- Server errors with an envelope-free body ---
      case 'invalid_payload':
        return 'The server rejected the request data. Check the fields and '
            'try again.';
      case 'conflict':
        return 'The request conflicts with the current server state. '
            'Refresh and try again.';
      case 'internal_error':
        return 'The HostelPass server hit an internal error. Try again '
            'shortly.';
      // Legacy transport codes — still produced directly by the camera
      // enrollment flow; not generated by ApiClient anymore.
      case 'local_network_unavailable':
        return 'No internet connection. The roster cannot be loaded offline — '
            'it will work once you are back online.';
      case 'local_server_unreachable':
        return 'Cannot reach the hostel server right now. Nothing is changed '
            'on the server until it confirms. Try again shortly.';
      case 'rate_limited':
        return 'Too many attempts. Please wait a minute before trying again.';
      case 'forbidden':
        return 'You do not have permission for this action.';
      case 'not_found':
        return 'That item could not be found.';
      // --- Camera (client, face enrollment) ---
      case 'local_camera_permission_denied':
        return 'Camera permission is required for face enrollment. Enable it in app settings.';
      case 'local_no_face':
        return 'No face detected. Position the face inside the oval.';
      case 'local_multiple_faces':
        return 'More than one face detected. Only the student being enrolled may be in frame.';
      case 'local_face_occluded':
        return 'Face not clear enough. Remove obstructions, look straight at the camera.';
      case 'local_low_light':
        return 'Lighting is too poor for enrollment. Face a light source and retry.';
      case 'local_capture_failed':
        return 'The photo could not be taken or read. Nothing was captured '
            'or saved — retry.';
      case 'local_detector_failed':
        return 'The on-device face detector failed. Nothing was captured or '
            'saved — retry, or close and reopen this screen.';
      default:
        return null;
    }
  }

  @override
  String toString() => 'AppException($code, $details)';
}

/// Shows a compact, design-system-styled error bar. Reused across screens.
class ErrorBar extends StatelessWidget {
  const ErrorBar({
    super.key,
    required this.message,
    this.onRetry,
    this.icon = Icons.error_outline,
  });

  final String message;
  final VoidCallback? onRetry;
  final IconData icon;

  @override
  Widget build(BuildContext context) {
    return Container(
      padding: const EdgeInsets.all(12),
      decoration: BoxDecoration(
        color: const Color(0xFFFFDAD6),
        borderRadius: BorderRadius.circular(8),
      ),
      child: Row(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Icon(icon, size: 20, color: const Color(0xFF93000A)),
          const SizedBox(width: 10),
          Expanded(
            child: Text(
              message,
              style: const TextStyle(
                fontFamily: 'Inter',
                fontSize: 13,
                height: 18 / 13,
                color: Color(0xFF93000A),
              ),
            ),
          ),
          if (onRetry != null)
            GestureDetector(
              onTap: onRetry,
              child: const Padding(
                padding: EdgeInsets.only(left: 8, top: 1),
                child: Text(
                  'Retry',
                  style: TextStyle(
                    fontFamily: 'Inter',
                    fontSize: 13,
                    fontWeight: FontWeight.w700,
                    color: Color(0xFF93000A),
                    decoration: TextDecoration.underline,
                  ),
                ),
              ),
            ),
        ],
      ),
    );
  }
}
